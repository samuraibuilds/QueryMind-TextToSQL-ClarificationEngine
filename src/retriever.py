import sqlite3
import os
from dotenv import load_dotenv

load_dotenv()
DB_PATH = os.getenv("DATABASE_PATH", "data/ecommerce.db")

GOLDEN_EXAMPLES = [
    {
        "keywords": ["city", "state", "location", "where"],
        "user_query": "Find total sales revenue from customers living in Sao Paulo",
        "sql": "SELECT SUM(o.payment_value) FROM orders o JOIN customers c ON o.customer_id = c.customer_id WHERE c.customer_city = 'Sao Paulo';"
    },
    {
        "keywords": ["heavy", "weight", "light"],
        "user_query": "List products ordered that weigh more than 1000 grams",
        "sql": "SELECT DISTINCT p.product_id, p.product_category_name FROM products p JOIN orders o ON p.product_id = o.product_id WHERE p.product_weight_g > 1000;"
    },
    {
        "keywords": ["revenue", "spent", "total", "sales", "category"],
        "user_query": "What is the total revenue generated by electronics?",
        "sql": "SELECT SUM(o.payment_value) FROM orders o JOIN products p ON o.product_id = p.product_id WHERE p.product_category_name = 'electronics';"
    }
]

def get_all_schema_metadata() -> str:
    """Fetches schema docs from database and unpacks variables flawlessly."""
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute("SELECT table_name, column_details, business_description FROM agent_schema_metadata;")
    rows = cursor.fetchall()
    conn.close()
    
    context_string = "DATABASE SCHEMA METADATA:\n"
    for row in rows:
        table_name, columns, description = row
        context_string += f"\n- Table: {table_name}\n"
        context_string += f"  Columns: {columns}\n"
        context_string += f"  Description: {description}\n"
    return context_string

def get_dynamic_few_shots(user_query: str) -> str:
    """Parses keywords out of the user query and selectively grabs matching expert templates."""
    selected_examples = []
    query_clean = user_query.lower()
    
    for example in GOLDEN_EXAMPLES:
        if any(keyword in query_clean for keyword in example["keywords"]):
            selected_examples.append(example)
            
    if not selected_examples:
        selected_examples = [GOLDEN_EXAMPLES[0]]
        
    few_shot_string = "\nRELEVANT EXPERT EXAMPLES FOR REFERENCE:\n"
    for ex in selected_examples:
        few_shot_string += f"Question: {ex['user_query']}\nSQL: {ex['sql']}\n\n"
        
    return few_shot_string

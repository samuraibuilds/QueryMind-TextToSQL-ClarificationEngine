import sys
from src.agent import analyze_and_route_query
from src.guardrails import is_sql_query_safe
from src.executor import execute_sql_query, automatic_error_correction_loop

def run_text_to_sql_pipeline(user_prompt: str):
    print(f"\n🚀 Incoming User Request: '{user_prompt}'")
    
    # 1. Route query through the Clarification / Generation Engine
    agent_decision = analyze_and_route_query(user_prompt)
    
    # Check if the agent flagged the request as too ambiguous
    if agent_decision.get("is_ambiguous"):
        print("\n🤔 [Clarification Engine Triggered]")
        print(f"👉 Agent Question: {agent_decision.get('clarification_message')}")
        return

    # Extract generated query if clear
    generated_sql = agent_decision.get("generated_sql")
    print(f"\n🧠 [SQL Generation Node Successful]")
    print(f"👉 Reasoning: {agent_decision.get('reasoning')}")
    print(f"👉 Generated SQL: {generated_sql}")

    # 2. Pass query through the Security Guardrails
    is_safe, guardrail_message = is_sql_query_safe(generated_sql)
    if not is_safe:
        print(f"\n🛑 [Guardrail Block]: {guardrail_message}")
        return
    print("🔒 [Guardrail Status]: Query passed security protocols.")

    # 3. Execute query on Database with automated repair loop
    success, columns, result_data = execute_sql_query(generated_sql)
    
    if not success:
        # DB execution failed (e.g. schema mapping typo) -> trigger repair loop
        error_msg = result_data  # SQLite error string
        healed_sql = automatic_error_correction_loop(generated_sql, error_msg)
        
        if healed_sql:
            print(f"✨ [Self-Healing Complete]: Retrying with corrected query...")
            print(f"👉 Healed SQL: {healed_sql}")
            success, columns, result_data = execute_sql_query(healed_sql)
        else:
            print("❌ [Execution Failure]: System was unable to auto-correct this query block.")
            return

    # 4. Display formatted results
    print(f"\n📊 [Query Results Matrix]:")
    print(f"Columns: {columns}")
    for row in result_data:
        print(f"Row data -> {row}")

if __name__ == "__main__":
    print("==================================================")
    print("  TEXT-TO-SQL VISUAL AGENT DEMO PIPELINE READY")
    print("==================================================")
    
    #Update line 57 inside main.py to target our complex Kaggle schema structures
    run_text_to_sql_pipeline("What is the total revenue generated by electronics category sales?")

